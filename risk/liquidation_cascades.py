"""Institutional Continuous Dynamic Margin Health & Multi-Tier Liquidation Cascades Engine.

Simulates and manages real-time solvency stress, collateral haircut decay curves,
maintenance margin buffer degradation, tiered liquidation ladders (staged partial unwinds,
hedge substitution, emergency capital injection calls), and cascade contagion analysis.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime, timezone
from enum import Enum
import math
from typing import Any, Dict, List, Optional, Tuple

import numpy as np


class SolvencyState(str, Enum):
    """Institutional solvency and margin health tier."""
    OPTIMAL = "OPTIMAL"                     # Margin Usage < 50%
    ELEVATED_RISK = "ELEVATED_RISK"         # 50% <= Usage < 75%
    MARGIN_DEFICIT = "MARGIN_DEFICIT"       # 75% <= Usage < 90%
    CRITICAL_UNWIND = "CRITICAL_UNWIND"     # 90% <= Usage < 100%
    INSOLVENT_DEFAULT = "INSOLVENT_DEFAULT" # Usage >= 100% (Equity < Maintenance Margin)


class LiquidationStage(str, Enum):
    """Stage in tiered liquidation ladder."""
    STAGE_0_INACTIVE = "STAGE_0_INACTIVE"               # No liquidation needed
    STAGE_1_CAPITAL_CALL = "STAGE_1_CAPITAL_CALL"       # Request margin call / sweep unencumbered cash
    STAGE_2_HEDGE_SUBSTITUTION = "STAGE_2_HEDGE_SUB"    # Synthetic delta-hedge to freeze VaR expansion
    STAGE_3_PARTIAL_UNWIND = "STAGE_3_PARTIAL_UNWIND"   # Unwind 25% of highest margin-consumption position
    STAGE_4_AGGRESSIVE_DELEVERAGE = "STAGE_4_DELEVERAGE"# Liquidate 50-75% across highest risk positions
    STAGE_5_FULL_CLOSEOUT = "STAGE_5_FULL_CLOSEOUT"     # Complete portfolio closeout & insurance fund draw


@dataclass(frozen=True)
class DynamicCollateralAsset:
    """Collateral asset subject to dynamic non-linear haircut decay."""
    asset: str
    quantity: float
    base_mark_price: float
    base_haircut: float = 0.05
    volatility_haircut_sensitivity: float = 1.2
    concentration_haircut_penalty: float = 0.5  # Additional haircut per % portfolio concentration

    def calculate_effective_haircut(
        self,
        asset_volatility: float,
        portfolio_concentration_pct: float,
        market_stress_multiplier: float = 1.0,
    ) -> float:
        """Dynamic haircut = min(0.99, base + sens * vol * stress + conc_pen * max(0, conc - 0.25))."""
        stress_haircut = self.base_haircut + (
            self.volatility_haircut_sensitivity * asset_volatility * market_stress_multiplier
        )
        if self.asset.upper() in ("USD", "USDC", "USDT"):
            conc_penalty = 0.0
        else:
            conc_excess = max(0.0, portfolio_concentration_pct - 0.25)
            conc_penalty = self.concentration_haircut_penalty * conc_excess
        total_haircut = stress_haircut + conc_penalty
        return float(np.clip(total_haircut, 0.0, 0.99))

    def get_collateral_value(
        self,
        current_price: float,
        effective_haircut: float,
    ) -> float:
        nominal = self.quantity * current_price
        return float(max(0.0, nominal * (1.0 - effective_haircut)))


@dataclass
class TieredLiquidationOrder:
    """Actionable liquidation child order generated by the cascade ladder."""
    order_id: str
    symbol: str
    side: str  # "SELL" for longs, "BUY" for shorts
    quantity: float
    estimated_price: float
    order_type: str = "IOC_LIMIT"
    stage: LiquidationStage = LiquidationStage.STAGE_3_PARTIAL_UNWIND
    margin_freed_usd: float = 0.0
    expected_realized_loss_usd: float = 0.0
    liquidation_fee_usd: float = 0.0

    def to_dict(self) -> Dict[str, Any]:
        return {
            "order_id": self.order_id,
            "symbol": self.symbol,
            "side": self.side,
            "quantity": float(self.quantity),
            "estimated_price": float(self.estimated_price),
            "order_type": self.order_type,
            "stage": self.stage.value,
            "margin_freed_usd": float(self.margin_freed_usd),
            "expected_realized_loss_usd": float(self.expected_realized_loss_usd),
            "liquidation_fee_usd": float(self.liquidation_fee_usd),
        }


@dataclass(frozen=True)
class LiquidationLadderPlan:
    """Comprehensive multi-tier liquidation response plan."""
    plan_id: str
    timestamp_utc: datetime
    solvency_state: SolvencyState
    current_margin_usage_pct: float
    target_margin_usage_pct: float
    required_margin_reduction_usd: float
    recommended_capital_injection_usd: float
    recommended_hedge_delta: Dict[str, float]
    liquidation_orders: List[TieredLiquidationOrder]
    total_margin_to_be_freed_usd: float
    projected_post_action_margin_usage_pct: float
    insurance_fund_draw_required_usd: float

    def to_dict(self) -> Dict[str, Any]:
        return {
            "plan_id": self.plan_id,
            "timestamp_utc": self.timestamp_utc.isoformat(),
            "solvency_state": self.solvency_state.value,
            "current_margin_usage_pct": float(self.current_margin_usage_pct),
            "target_margin_usage_pct": float(self.target_margin_usage_pct),
            "required_margin_reduction_usd": float(self.required_margin_reduction_usd),
            "recommended_capital_injection_usd": float(self.recommended_capital_injection_usd),
            "recommended_hedge_delta": dict(self.recommended_hedge_delta),
            "liquidation_orders": [o.to_dict() for o in self.liquidation_orders],
            "total_margin_to_be_freed_usd": float(self.total_margin_to_be_freed_usd),
            "projected_post_action_margin_usage_pct": float(self.projected_post_action_margin_usage_pct),
            "insurance_fund_draw_required_usd": float(self.insurance_fund_draw_required_usd),
        }


