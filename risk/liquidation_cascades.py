class DynamicMarginHealthEngine:
    """Institutional Dynamic Margin Health, Haircut Decay & Liquidation Cascades Engine.

    Key Features:
    1. Non-linear Dynamic Collateral Haircuts:
       Incorporates real-time asset volatility and portfolio concentration penalties.
    2. Continuous Solvency State Classification:
       Classifies portfolio into OPTIMAL, ELEVATED_RISK, MARGIN_DEFICIT, CRITICAL_UNWIND, INSOLVENT_DEFAULT.
    3. Multi-Tier Liquidation Ladder Generator:
       - Evaluates capital calls / sweeps first.
       - Generates delta hedge substitution recommendations to freeze portfolio risk.
       - Staged partial unwinding (25% -> 50% -> 100%) targeting highest margin-consumption positions.
       - Incorporates liquidation fee penalties and market impact slippage.
    4. Extreme Solvency Stress Harness:
       Simulates simultaneous price crashes (-10% to -50%) and volatility spikes to verify solvency survival.
    """

    def __init__(
        self,
        liquidation_fee_rate: float = 0.005,  # 50 bps liquidation penalty
        target_healthy_usage_pct: float = 0.70,  # Aim to restore margin usage to 70%
    ) -> None:
        self.liquidation_fee_rate = float(liquidation_fee_rate)
        self.target_healthy_usage_pct = float(target_healthy_usage_pct)

    def evaluate_solvency_and_cascade(
        self,
        collateral_assets: List[DynamicCollateralAsset],
        positions: List[Dict[str, Any]],  # [{symbol, side, quantity, mark_price, mm_rate, entry_price}, ...]
        asset_volatilities: Optional[Dict[str, float]] = None,
        market_stress_multiplier: float = 1.0,
    ) -> Tuple[LiquidationLadderPlan, SolvencyState]:
        """Compute live dynamic margin health and formulate staged liquidation ladder if required."""
        vols = asset_volatilities or {}

        # 1. Calculate dynamic collateral value with concentration penalties
        total_nominal_collateral = sum(c.quantity * c.base_mark_price for c in collateral_assets)
        total_effective_collateral = 0.0

        for col in collateral_assets:
            conc = (col.quantity * col.base_mark_price) / max(total_nominal_collateral, 1e-6)
            default_vol = 0.0 if col.asset.upper() in ("USD", "USDC", "USDT") else 0.20
            vol = vols.get(col.asset.upper(), default_vol)
            haircut = col.calculate_effective_haircut(
                asset_volatility=vol,
                portfolio_concentration_pct=conc,
                market_stress_multiplier=market_stress_multiplier,
            )
            col_val = col.get_collateral_value(col.base_mark_price, haircut)
            total_effective_collateral += col_val

        # 2. Evaluate positions maintenance margin and unrealized PnL
        total_unrealized_pnl = 0.0
        total_maintenance_margin = 0.0
        position_details: List[Dict[str, Any]] = []

        for p in positions:
            sym = p["symbol"]
            side = p["side"].upper()
            qty = float(p["quantity"])
            mark = float(p["mark_price"])
            entry = float(p.get("entry_price", mark))
            mm_rate = float(p.get("mm_rate", 0.05))

            notional = abs(qty * mark)
            mm_req = notional * mm_rate
            total_maintenance_margin += mm_req

            if side == "LONG":
                u_pnl = (mark - entry) * qty
            else:
                u_pnl = (entry - mark) * qty
            total_unrealized_pnl += u_pnl

            position_details.append({
                "symbol": sym,
                "side": side,
                "quantity": qty,
                "mark_price": mark,
                "entry_price": entry,
                "notional": notional,
                "mm_rate": mm_rate,
                "mm_req": mm_req,
                "u_pnl": u_pnl,
            })

        # Effective Equity = Collateral Value + Unrealized PnL
        effective_equity = total_effective_collateral + total_unrealized_pnl
        if total_maintenance_margin > 1e-6:
            margin_usage_pct = (total_maintenance_margin / max(effective_equity, 1e-6))
        else:
            margin_usage_pct = 0.0

        # Classify Solvency State
        if effective_equity <= total_maintenance_margin or effective_equity <= 0:
            solvency_state = SolvencyState.INSOLVENT_DEFAULT
        elif margin_usage_pct >= 0.90:
            solvency_state = SolvencyState.CRITICAL_UNWIND
        elif margin_usage_pct >= 0.75:
            solvency_state = SolvencyState.MARGIN_DEFICIT
        elif margin_usage_pct >= 0.50:
            solvency_state = SolvencyState.ELEVATED_RISK
        else:
            solvency_state = SolvencyState.OPTIMAL

        # Build Liquidation Ladder
        plan = self._build_liquidation_ladder(
            solvency_state=solvency_state,
            current_usage_pct=margin_usage_pct,
            effective_equity=effective_equity,
            total_mm=total_maintenance_margin,
            position_details=position_details,
        )

        return plan, solvency_state

    def simulate_solvency_stress(
        self,
        collateral_assets: List[DynamicCollateralAsset],
        positions: List[Dict[str, Any]],
        scenario_name: str = "Flash Crash 30%",
        price_shock_pct: float = -0.30,
        volatility_shock_multiplier: float = 2.5,
    ) -> SolvencyStressSimulationResult:
        """Simulate portfolio solvency under catastrophic price drops and volatility shocks."""
        pre_plan, _ = self.evaluate_solvency_and_cascade(
            collateral_assets=collateral_assets,
            positions=positions,
            market_stress_multiplier=1.0,
        )
        pre_equity = sum(c.quantity * c.base_mark_price for c in collateral_assets)

        # Apply Shock
        shocked_collateral: List[DynamicCollateralAsset] = []
        for c in collateral_assets:
            shocked_price = c.base_mark_price * (1.0 + price_shock_pct)
            shocked_collateral.append(
                DynamicCollateralAsset(
                    asset=c.asset,
                    quantity=c.quantity,
                    base_mark_price=shocked_price,
                    base_haircut=c.base_haircut,
                    volatility_haircut_sensitivity=c.volatility_haircut_sensitivity,
                    concentration_haircut_penalty=c.concentration_haircut_penalty,
                )
            )

        shocked_positions: List[Dict[str, Any]] = []
        for p in positions:
            p_copy = dict(p)
            p_copy["mark_price"] = p["mark_price"] * (1.0 + price_shock_pct)
            shocked_positions.append(p_copy)

        post_plan, post_state = self.evaluate_solvency_and_cascade(
            collateral_assets=shocked_collateral,
            positions=shocked_positions,
            market_stress_multiplier=volatility_shock_multiplier,
        )

        post_equity = post_plan.total_margin_to_be_freed_usd  # Context
        # Compute post-shock metrics
        total_nominal_col = sum(c.quantity * c.base_mark_price for c in shocked_collateral)
        eff_col = sum(
            c.get_collateral_value(
                c.base_mark_price,
                c.calculate_effective_haircut(0.35, 0.3, volatility_shock_multiplier),
            )
            for c in shocked_collateral
        )
        post_u_pnl = 0.0
        post_mm = 0.0
        for p in shocked_positions:
            notional = abs(p["quantity"] * p["mark_price"])
            post_mm += notional * p.get("mm_rate", 0.05)
            if p["side"].upper() == "LONG":
                post_u_pnl += (p["mark_price"] - p.get("entry_price", p["mark_price"])) * p["quantity"]
            else:
                post_u_pnl += (p.get("entry_price", p["mark_price"]) - p["mark_price"]) * p["quantity"]

        final_post_equity = eff_col + post_u_pnl
        is_solvent = (final_post_equity > post_mm and final_post_equity > 0)
        shortfall = max(0.0, post_mm - final_post_equity) if not is_solvent else 0.0

        if post_state == SolvencyState.INSOLVENT_DEFAULT:
            breach_stage = LiquidationStage.STAGE_5_FULL_CLOSEOUT
        elif post_state == SolvencyState.CRITICAL_UNWIND:
            breach_stage = LiquidationStage.STAGE_4_AGGRESSIVE_DELEVERAGE
        elif post_state == SolvencyState.MARGIN_DEFICIT:
            breach_stage = LiquidationStage.STAGE_3_PARTIAL_UNWIND
        elif post_state == SolvencyState.ELEVATED_RISK:
            breach_stage = LiquidationStage.STAGE_1_CAPITAL_CALL
        else:
            breach_stage = LiquidationStage.STAGE_0_INACTIVE

        post_usage = (post_mm / max(final_post_equity, 1e-6)) if final_post_equity > 0 else 999.0

        return SolvencyStressSimulationResult(
            shock_scenario_name=scenario_name,
            price_shock_pct=float(price_shock_pct),
            volatility_shock_multiplier=float(volatility_shock_multiplier),
            pre_shock_equity=float(pre_equity),
            post_shock_equity=float(final_post_equity),
            post_shock_effective_collateral=float(eff_col),
            post_shock_maintenance_margin=float(post_mm),
            post_shock_margin_usage_pct=float(post_usage),
            is_solvent=bool(is_solvent),
            breach_stage_reached=breach_stage,
            estimated_shortfall_usd=float(shortfall),
        )

    # -------------------------------------------------------------------------
    # Internal Ladder Builder
    # -------------------------------------------------------------------------

    def _build_liquidation_ladder(
        self,
        solvency_state: SolvencyState,
        current_usage_pct: float,
        effective_equity: float,
        total_mm: float,
        position_details: List[Dict[str, Any]],
    ) -> LiquidationLadderPlan:
        """Formulate multi-stage liquidation plan targeting healthy margin ratio."""
        import uuid
        plan_id = f"liq_{uuid.uuid4().hex[:8]}"

        if solvency_state in (SolvencyState.OPTIMAL, SolvencyState.ELEVATED_RISK):
            # No liquidation orders needed; stage 1 capital call notification if ELEVATED_RISK
            capital_call = 0.0
            if solvency_state == SolvencyState.ELEVATED_RISK:
                # Advise buffer top-up
                target_equity = total_mm / self.target_healthy_usage_pct
                capital_call = max(0.0, target_equity - effective_equity)

            return LiquidationLadderPlan(
                plan_id=plan_id,
                timestamp_utc=datetime.now(timezone.utc),
                solvency_state=solvency_state,
                current_margin_usage_pct=round(current_usage_pct, 4),
                target_margin_usage_pct=self.target_healthy_usage_pct,
                required_margin_reduction_usd=0.0,
                recommended_capital_injection_usd=round(capital_call, 2),
                recommended_hedge_delta={},
                liquidation_orders=[],
                total_margin_to_be_freed_usd=0.0,
                projected_post_action_margin_usage_pct=round(current_usage_pct, 4),
                insurance_fund_draw_required_usd=0.0,
            )

        # We have MARGIN_DEFICIT, CRITICAL_UNWIND, or INSOLVENT_DEFAULT
        # Required MM reduction: Target MM = Equity * target_healthy_usage_pct
        target_mm = max(0.0, effective_equity * self.target_healthy_usage_pct)
        required_mm_reduction = max(0.0, total_mm - target_mm)

        # Sort positions by margin requirement descending (highest risk first)
        sorted_pos = sorted(position_details, key=lambda p: p["mm_req"], reverse=True)

        liquidation_orders: List[TieredLiquidationOrder] = []
        freed_mm = 0.0
        insurance_draw = 0.0

        if solvency_state == SolvencyState.INSOLVENT_DEFAULT:
            # Full closeout across all positions
            stage = LiquidationStage.STAGE_5_FULL_CLOSEOUT
            unwind_fraction = 1.0
            insurance_draw = max(0.0, total_mm - effective_equity)
        elif solvency_state == SolvencyState.CRITICAL_UNWIND:
            stage = LiquidationStage.STAGE_4_AGGRESSIVE_DELEVERAGE
            unwind_fraction = 0.60
        else:
            stage = LiquidationStage.STAGE_3_PARTIAL_UNWIND
            unwind_fraction = 0.30

        for i, pos in enumerate(sorted_pos, start=1):
            if freed_mm >= required_mm_reduction and solvency_state != SolvencyState.INSOLVENT_DEFAULT:
                break

            close_qty = pos["quantity"] * unwind_fraction
            if close_qty <= 1e-6:
                continue

            close_side = "SELL" if pos["side"] == "LONG" else "BUY"
            freed_pos_mm = pos["mm_req"] * unwind_fraction
            notional = close_qty * pos["mark_price"]
            liq_fee = notional * self.liquidation_fee_rate

            # Realized loss
            if pos["side"] == "LONG":
                realized_pnl = (pos["mark_price"] - pos["entry_price"]) * close_qty
            else:
                realized_pnl = (pos["entry_price"] - pos["mark_price"]) * close_qty

            order = TieredLiquidationOrder(
                order_id=f"LIQ_{i}_{pos['symbol']}",
                symbol=pos["symbol"],
                side=close_side,
                quantity=round(close_qty, 6),
                estimated_price=pos["mark_price"],
                order_type="IOC_LIMIT",
                stage=stage,
                margin_freed_usd=round(freed_pos_mm, 2),
                expected_realized_loss_usd=round(realized_pnl, 2),
                liquidation_fee_usd=round(liq_fee, 2),
            )
            liquidation_orders.append(order)
            freed_mm += freed_pos_mm

        # Projected usage
        post_mm = max(0.0, total_mm - freed_mm)
        post_usage = (post_mm / max(effective_equity, 1e-6)) if effective_equity > 0 else 0.0

        # Recommended synthetic hedge delta for delta-neutralization
        hedge_deltas = {}
        for p in position_details:
            sym = p["symbol"]
            curr_delta = p["quantity"] if p["side"] == "LONG" else -p["quantity"]
            if abs(curr_delta) > 1e-6:
                hedge_deltas[sym] = round(-curr_delta * 0.5, 4)  # 50% delta hedge

        return LiquidationLadderPlan(
            plan_id=plan_id,
            timestamp_utc=datetime.now(timezone.utc),
            solvency_state=solvency_state,
            current_margin_usage_pct=round(current_usage_pct, 4),
            target_margin_usage_pct=self.target_healthy_usage_pct,
            required_margin_reduction_usd=round(required_mm_reduction, 2),
            recommended_capital_injection_usd=0.0,
            recommended_hedge_delta=hedge_deltas,
            liquidation_orders=liquidation_orders,
            total_margin_to_be_freed_usd=round(freed_mm, 2),
            projected_post_action_margin_usage_pct=round(post_usage, 4),
            insurance_fund_draw_required_usd=round(insurance_draw, 2),
        )
